def die(msg):
    print(f"[patch_v12] ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def sh(cmd, check=True):
    print(f"[patch_v12] $ {' '.join(cmd)}")
    return subprocess.run(cmd, check=check)


def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def write(path, content):
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def step_write_font():
    os.makedirs(FONT_DIR, exist_ok=True)
    data = base64.b64decode(BRAVOON_B64)
    if os.path.exists(FONT_PATH) and os.path.getsize(FONT_PATH) == len(data):
        print("[patch_v12] Bravoon.ttf already present, skipping.")
        return
    with open(FONT_PATH, "wb") as f:
        f.write(data)
    print(f"[patch_v12] wrote {FONT_PATH} ({len(data)} bytes)")


def step_pubspec():
    if not os.path.exists(PUBSPEC_FILE):
        die("pubspec.yaml not found")
    content = read(PUBSPEC_FILE)
    if "family: Bravoon" in content:
        print("[patch_v12] pubspec.yaml already lists Bravoon, skipping.")
        return
    marker = "    - family: Alyamama\n      fonts:\n        - asset: assets/fonts/Alyamama-Bold.ttf\n          weight: 700\n"
    if marker not in content:
        die("could not find the Alyamama font block in pubspec.yaml to anchor on")
    addition = marker + "    - family: Bravoon\n      fonts:\n        - asset: assets/fonts/Bravoon.ttf\n          weight: 400\n"
    content = content.replace(marker, addition, 1)
    write(PUBSPEC_FILE, content)
    print("[patch_v12] added Bravoon font block to pubspec.yaml")


def step_theme():
    content = read(THEME_FILE)
    if "static const bravoon = 'Bravoon';" in content:
        print("[patch_v12] theme.dart already patched, skipping.")
        return

    # 1. Register the font in AppFonts.
    anchor = "  static const aligarh = 'Aligarh';"
    if anchor not in content:
        die("could not find AppFonts.aligarh anchor in theme.dart")
    content = content.replace(
        anchor,
        anchor
        + "\n  /// Title font -- headlineLarge/headlineMedium/titleLarge and\n"
        + "  /// AppBar titles app-wide. Added by patch_v12.\n"
        + "  static const bravoon = 'Bravoon';",
        1,
    )

    # 2. Swap the 12 headline/title TextStyles (3 styles x 4 themes) from
    #    Aligarh to Bravoon.
    pattern = re.compile(
        r"(headlineLarge:  TextStyle\(fontFamily: )'Aligarh'"
        r"|(headlineMedium: TextStyle\(fontFamily: )'Aligarh'"
        r"|(titleLarge:     TextStyle\(fontFamily: )'Aligarh'"
    )
    content, n = pattern.subn(lambda m: (m.group(1) or m.group(2) or m.group(3)) + "'Bravoon'", content)
    if n != 12:
        die(f"expected to patch 12 headline/title TextStyles (3 x 4 themes), patched {n} -- theme.dart layout changed, check by hand")

    # 3. Swap the two Ramadan AppBar titleTextStyle blocks.
    ramadan_title_pattern = re.compile(
        r"(titleTextStyle: TextStyle\(\n\s*fontFamily: )'Aligarh'(, fontWeight: FontWeight\.w800,)"
    )
    content, n2 = ramadan_title_pattern.subn(r"\1'Bravoon'\2", content)
    if n2 != 2:
        die(f"expected to patch 2 Ramadan AppBar titleTextStyles, patched {n2} -- check by hand")

    write(THEME_FILE, content)
    print(f"[patch_v12] theme.dart: registered AppFonts.bravoon, retitled {n} textTheme styles + {n2} AppBar titles")


def step_splash():
    content = read(SPLASH_FILE)
    old = "'assets/icons/mosque_mark/mosque_medium.png',"
    new = "'assets/logo.png',"
    if new in content and old not in content:
        print("[patch_v12] splash_screen.dart already patched, skipping.")
        return
    if old not in content:
        die("could not find the mosque_medium.png reference in splash_screen.dart")
    content = content.replace(old, new, 1)
    write(SPLASH_FILE, content)
    print("[patch_v12] splash_screen.dart now shows assets/logo.png instead of the mosque mark")


def main():
    if os.path.exists(STAMP_FILE):
        print("[patch_v12] already applied (stamp file present). Nothing to do.")
        return

    for f in (THEME_FILE, SPLASH_FILE, PUBSPEC_FILE):
        if not os.path.exists(f):
            die(f"expected file missing: {f} -- run this from the repo root")

    step_write_font()
    step_pubspec()
    step_theme()
    step_splash()

    with open(STAMP_FILE, "w") as f:
        f.write("applied\n")

    sh(["git", "add", "-A"])
    sh(["git", "commit", "-m",
        "feat: add Bravoon title font (headlines/titles/AppBar), fix splash showing mosque icon instead of app logo"])
    sh(["git", "push"])
    print("[patch_v12] done.")


if __name__ == "__main__":
    main()
