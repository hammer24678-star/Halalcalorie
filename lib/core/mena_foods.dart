// Offline food database for the Arabic kitchen: Egyptian, Levantine, Gulf and
// Maghreb dishes, breads, sweets, dates and drinks. Values are per 100 g (per
// 100 ml for drinks) and are typical figures for home / restaurant cooking, so
// the UI always labels them as estimates. Each food carries the servings people
// actually use here (رغيف، طبق، قرص، فنجان…) with their weight in grams.
//
// Search folds Arabic spelling (أ/إ/آ→ا، ة→ه، ى→ي، tashkeel) and indexes Latin
// transliterations, so كشري / كشرى / koshary / kushari all find the same dish.

class MenaServing {
  final String ar;
  final String en;
  final double grams;
  const MenaServing(this.ar, this.en, this.grams);
}

class MenaFood {
  final String id;

  /// One of [kMenaCategories] ids.
  final String cat;

  /// 'eg' Egyptian, 'lv' Levantine, 'gulf' Gulf, 'mg' Maghreb, 'me' pan-Arab.
  final String region;
  final String ar;
  final String en;

  /// Extra search words: transliterations and spelling variants.
  final String aliases;

  /// Per 100 g (per 100 ml when [isLiquid]).
  final double kcal;
  final double protein;
  final double carbs;
  final double fat;

  /// Typical servings, most common first.
  final List<MenaServing> servings;

  const MenaFood({
    required this.id,
    required this.cat,
    required this.region,
    required this.ar,
    required this.en,
    required this.aliases,
    required this.kcal,
    required this.protein,
    required this.carbs,
    required this.fat,
    required this.servings,
  });

  bool get isLiquid => cat == 'drinks';

  MenaServing get defaultServing => servings.first;

  double kcalFor(double grams) => kcal * grams / 100.0;
}

