class MenaFoods {
  MenaFoods._();

  static final RegExp _marks = RegExp('[ً-ٰٟـ]');
  static final RegExp _punct = RegExp(r'[^\p{L}\p{N}\s]', unicode: true);
  static final RegExp _spaces = RegExp(r'\s+');

  /// Lower-cases and folds Arabic spelling variants so searches match.
  static String fold(String input) {
    var t = input.toLowerCase();
    t = t.replaceAll(_marks, '');
    t = t
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ٱ', 'ا')
        .replaceAll('ى', 'ي')
        .replaceAll('ة', 'ه')
        .replaceAll('ؤ', 'و')
        .replaceAll('ئ', 'ي');
    t = t.replaceAll(_punct, ' ');
    return t.replaceAll(_spaces, ' ').trim();
  }

  static final Map<String, String> _names = {
    for (final f in kMenaFoods) f.id: '${fold(f.ar)} ${fold(f.en)}',
  };
  static final Map<String, String> _haystack = {
    for (final f in kMenaFoods)
      f.id: '${fold(f.ar)} ${fold(f.en)} ${fold(f.aliases)}',
  };
  static final Map<String, MenaFood> _byId = {
    for (final f in kMenaFoods) f.id: f,
  };

  static MenaFood? byId(String id) => _byId[id];

  static List<MenaFood> inCategory(String cat) =>
      [for (final f in kMenaFoods) if (f.cat == cat) f];

  static List<MenaFood> featured() =>
      [for (final id in kMenaFeatured) if (_byId[id] != null) _byId[id]!];

  /// Foods whose Arabic name, English name or aliases contain every word of
  /// [query]; names that start with the query come first.
  static List<MenaFood> search(String query, {int limit = 12}) {
    final folded = fold(query);
    if (folded.isEmpty) return const [];
    final tokens = <String>[];
    for (final w in folded.split(' ')) {
      if (w.isEmpty) continue;
      // Drop the Arabic definite article ("الكشري" -> "كشري").
      tokens.add(w.length > 3 && w.startsWith('ال') ? w.substring(2) : w);
    }
    if (tokens.isEmpty) return const [];

    final scored = <(int, int, MenaFood)>[];
    for (var i = 0; i < kMenaFoods.length; i++) {
      final f = kMenaFoods[i];
      final hay = _haystack[f.id]!;
      var all = true;
      for (final t in tokens) {
        if (!hay.contains(t)) {
          all = false;
          break;
        }
      }
      if (!all) continue;
      final names = _names[f.id]!;
      final words = names.split(' ');
      var score = 2;
      if (names.startsWith(tokens.first)) {
        score = 0;
      } else if (words.any((w) => w.startsWith(tokens.first))) {
        score = 1;
      }
      scored.add((score, i, f));
    }
    scored.sort((a, b) {
      final c = a.$1.compareTo(b.$1);
      return c != 0 ? c : a.$2.compareTo(b.$2);
    });
    return [for (final s in scored.take(limit)) s.$3];
  }
}
